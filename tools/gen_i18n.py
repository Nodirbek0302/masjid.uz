# Hand-written Cyrillic where plain transliteration would be wrong (loan words that need ь/ц etc.).
CYRL_FIX = {
    "map.err_tiles": "Харита маълумотлари юкланмаяпти (tiles.openfreemap.org). Интернет, VPN ёки тармоқ фильтрини текширинг.",
    "map.err_style": "Харита услубини юклаб бўлмади (tiles.openfreemap.org). Интернет, VPN ёки тармоқ фильтрини текширинг.",
}

PROTECT = re.compile(r"(\{[^}]*\}|tiles\.openfreemap\.org|Yandex Maps|OpenStreetMap contributors|OpenStreetMap|Telegram|VPN|HH:MM|ODbL|ADMIN_TOKEN|©|[\U0001F300-\U0001FAFF])")


def cyrillize(text):
    return "".join(part if PROTECT.fullmatch(part) else translit.to_cyrillic(part) for part in PROTECT.split(text))


def main():
    CYRL = {k: CYRL_FIX.get(k) or cyrillize(v) for k, v in UZ.items()}
    # UI chrome inside the Latin strings that must read naturally in Uzbek Cyrillic
    langs = {"uz": UZ, "uz-cyrl": CYRL, "ru": RU, "en": EN}
    base = set(UZ)
    ph = lambda s: sorted(re.findall(r"\{(\w+)\}", s))   # noqa: E731
    bad = []
    for name, d in langs.items():
        if set(d) != base:
            bad.append("%s: keys differ: missing=%s extra=%s" % (name, sorted(base - set(d)), sorted(set(d) - base)))
            continue
        for k in base:
            if ph(d[k]) != ph(UZ[k]):
                bad.append("%s: placeholder mismatch in %s" % (name, k))
    if bad:
        sys.exit("\n".join(bad))
    names = [["uz", "UZ", "Oʻzbekcha"], ["uz-cyrl", "ЎЗ", "Ўзбекча"], ["ru", "РУ", "Русский"], ["en", "EN", "English"]]
    out = ROOT / "web" / "i18n.js"
    tmpl = (ROOT / "tools" / "i18n.template.js").read_text(encoding="utf-8")
    js = tmpl.replace("/*DICT*/{}", json.dumps(langs, ensure_ascii=False, indent=1, sort_keys=True)).replace("/*LANGS*/[]", json.dumps(names, ensure_ascii=False))
    out.write_text("/* GENERATED by tools/gen_i18n.py: edit the tables there, not this file. */\n" + js, encoding="utf-8")
    print("wrote %s: %d keys x %d languages" % (out.relative_to(ROOT), len(base), len(langs)))
    if "--show-cyrl" in sys.argv:
        for k in sorted(UZ):
            print("%-24s %s\n%-24s %s" % (k, UZ[k], "", CYRL[k]))


if __name__ == "__main__":
    main()
